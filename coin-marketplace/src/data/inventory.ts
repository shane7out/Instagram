/** Build a full Coin (with computed marketplace price) from a raw record. */
function buildCoin(raw: RawCoin): Coin {
  const price = computePrice(raw.sourcePrice);
  const compareAtPrice = computeCompareAt(price);
  const source = SOURCES[raw.sourceId];
  return {
    id: `${raw.sourceId}:${raw.slug}`,
    slug: raw.slug,
    title: raw.title,
    categorySlug: raw.categorySlug,
    extraCategorySlugs: raw.extraCategorySlugs,
    year: raw.year,
    mintMark: raw.mintMark,
    mint: raw.mint,
    denomination: raw.denomination,
    series: raw.series,
    country: raw.country,
    metal: raw.metal,
    composition: raw.composition,
    weightGrams: raw.weightGrams,
    diameterMm: raw.diameterMm,
    gradingService: raw.gradingService,
    grade: raw.grade,
    gradeNumeric: raw.gradeNumeric,
    condition: raw.condition,
    certNumber: raw.certNumber,
    sourcePrice: raw.sourcePrice,
    price,
    compareAtPrice,
    images: [], // sample data uses generated medallions; real imports carry photo URLs
    description: raw.description,
    highlights: raw.highlights,
    rarityNote: raw.rarityNote,
    source,
    quantityAvailable: raw.quantityAvailable ?? 1,
    inStock: (raw.quantityAvailable ?? 1) > 0,
    lastSyncedAt: LAST_SYNCED,
    featured: raw.featured,
    isNew: raw.isNew,
  };
}

export const coins: Coin[] = RAW.map(buildCoin);
